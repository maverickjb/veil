int fb_init(void)
{
    memset(mbox_buf, 0, sizeof(mbox_buf));
    mbox_buf[0] = 35 * 4;
    mbox_buf[1] = 0;
    mbox_buf[2] = 0x48003; /* set phys wh */
    mbox_buf[3] = 8;
    mbox_buf[4] = 8;
    mbox_buf[5] = FB_W;
    mbox_buf[6] = FB_H;
    mbox_buf[7] = 0x48004; /* set virt wh */
    mbox_buf[8] = 8;
    mbox_buf[9] = 8;
    mbox_buf[10] = FB_W;
    mbox_buf[11] = FB_H;
    mbox_buf[12] = 0x48005; /* depth */
    mbox_buf[13] = 4;
    mbox_buf[14] = 4;
    mbox_buf[15] = 32;
    mbox_buf[16] = 0x48006; /* pixel order RGB */
    mbox_buf[17] = 4;
    mbox_buf[18] = 4;
    mbox_buf[19] = 1;
    mbox_buf[20] = 0x40001; /* allocate: req align, resp addr+size */
    mbox_buf[21] = 8;
    mbox_buf[22] = 8;
    mbox_buf[23] = 0x100000; /* 1 MiB align */
    mbox_buf[24] = 0;
    mbox_buf[25] = 0x40008; /* pitch */
    mbox_buf[26] = 4;
    mbox_buf[27] = 4;
    mbox_buf[28] = 0;
    mbox_buf[29] = 0;

    if (!mbox_call() || !mbox_buf[23]) {
        return -1;
    }

    fb_pa = mbox_buf[23] & 0x3fffffffu;
    fb_pitch = mbox_buf[28];
    if (fb_pitch < FB_W * 4) {
        fb_pitch = FB_W * 4;
    }
    /* Do not paint over Veil or the embedded QEMU_EFI.fd (0x80000..0x400000). */
    if (fb_pa < 0x400000ull) {
        return -1;
    }
    fb = (volatile uint32_t *)(uintptr_t)fb_pa;
    platform_clip_guest_ram(fb_pa, (size_t)fb_pitch * FB_H);
    fb_fill(COL_BG);
    fb_ready = 1;
    fb_header();
    hyp_printf("veil: fb pa %p pitch %u\n", (uint64_t)fb_pa, fb_pitch);
    return 0;
}

